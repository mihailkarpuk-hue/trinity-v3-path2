// Тринити Альфа — Блок 3 «Каталог»
// Загружает каталог.json, рисует меню из 4 групп, отслеживает активную клеточку,
// рассылает событие 'cellSelected' (Решение 5.2), обрабатывает стрелки в фокусе (Решение 5.3),
// автоматически выбирает стартовую клеточку (Решение 5.4).

(() => {
    'use strict';

    // === Конфиг ===
    const ПУТЬ_К_КАТАЛОГУ = '../../данные/клеточки/каталог.json';
    // Порядок групп в меню (фиксированный, чтобы Природа была сверху).
    const ПОРЯДОК_ГРУПП = ['буквица_живая', 'буквица', 'базис', 'музыка', 'голос', 'инструменты', 'природа', 'биология'];
    const ИМЕНА_ГРУПП = {
        'буквица_живая': '🎙 Буквица живая (голос)',
        'базис': 'Чистый базис',
        'буквица': 'Буквица',
        'музыка': 'Музыка',
        'природа': 'Природа',
        'биология': 'Биология',
        'голос': 'Голос',
        'инструменты': 'Инструменты',
    };

    // === DOM-якорь ===
    const корень_панели = document.getElementById('зона-каталог');
    if (!корень_панели) {
        console.error('[каталог] не найдена зона #зона-каталог');
        return;
    }
    const узел_паспорта = document.getElementById('паспорт');

    // === Состояние ===
    let клеточки_по_id = new Map();         // id → объект
    let группы = new Map();                 // имя → массив объектов (в порядке появления)
    let активный_id = null;
    let фокус_в_каталоге = false;

    // === Корневая разметка ===
    корень_панели.innerHTML = `
        <div class="каталог-корень" id="каталог-корень" tabindex="-1">
            <div class="каталог-заголовок">КАТАЛОГ</div>
            <div class="каталог-группы" id="каталог-группы"></div>
        </div>
    `;
    const корень = корень_панели.querySelector('#каталог-корень');
    const контейнер_групп = корень_панели.querySelector('#каталог-группы');

    // Отслеживание «фокус мой» (Решение 5.3) — на hover/click внутри панели.
    корень_панели.addEventListener('mouseenter', () => поставить_фокус(true));
    корень_панели.addEventListener('mouseleave', () => поставить_фокус(false));
    корень_панели.addEventListener('click',     () => поставить_фокус(true));
    корень_панели.addEventListener('focusin',   () => поставить_фокус(true));

    function поставить_фокус(да) {
        фокус_в_каталоге = да;
        корень.dataset.фокус = да ? 'да' : 'нет';
        // Глобальный флаг — плеер (Задание 7) читает window.__каталог_в_фокусе перед обработкой стрелок.
        window.__каталог_в_фокусе = да;
    }

    // === Загрузка ===
    (async function загрузить() {
        try {
            const ответ = await fetch(encodeURI(ПУТЬ_К_КАТАЛОГУ), { cache: 'no-store' });
            if (!ответ.ok) throw new Error('HTTP ' + ответ.status);
            const данные = await ответ.json();
            построить(данные);
        } catch (e) {
            console.error('[каталог] не удалось загрузить:', e);
            контейнер_групп.innerHTML =
                `<div style="padding:16px;color:var(--акцент-тёплый);font-size:12px;">
                   Не удалось загрузить каталог: ${e.message}
                 </div>`;
        }
    })();

    function построить(данные) {
        const список = Array.isArray(данные?.клеточки) ? данные.клеточки : [];
        if (!список.length) {
            контейнер_групп.innerHTML =
                '<div style="padding:16px;color:var(--текст-тусклый);">Каталог пуст.</div>';
            return;
        }

        // Группируем
        for (const кл of список) {
            клеточки_по_id.set(кл.id, кл);
            const г = кл.группа || 'неизвестно';
            if (!группы.has(г)) группы.set(г, []);
            группы.get(г).push(кл);
        }
        // Сортировка внутри группы по русскому названию
        for (const список_гр of группы.values()) {
            список_гр.sort((a, b) =>
                (a.название || a.id).localeCompare(b.название || b.id, 'ru'));
        }

        // Стартовая клеточка (Решение 5.4)
        const стартовая =
            (данные.стартовая_клеточка_id && клеточки_по_id.get(данные.стартовая_клеточка_id)) ||
            список.find(c => c['стартовая']) ||
            (группы.get('биология')?.[0]) ||
            список[0];

        // Сюрпризы: группы вне 4 стандартных
        const неизвестные = [...группы.keys()].filter(g => !ПОРЯДОК_ГРУПП.includes(g));
        if (неизвестные.length) {
            console.warn('[каталог] нестандартные группы:', неизвестные);
        }
        // Финальный порядок — стандартные + неизвестные в конце.
        const порядок = [
            ...ПОРЯДОК_ГРУПП.filter(g => группы.has(g)),
            ...неизвестные,
        ];

        // Рендер
        const фрагмент = document.createDocumentFragment();
        for (const имя_группы of порядок) {
            const список_гр = группы.get(имя_группы);
            const блок_группы = создать_блок_группы(имя_группы, список_гр);
            фрагмент.appendChild(блок_группы);
        }
        контейнер_групп.appendChild(фрагмент);

        // Раскрываем группу со стартовой клеточкой
        if (стартовая) раскрыть_группу(стартовая.группа, true);

        // Выбираем стартовую (без скролла к ней не имеет смысла — раскрытая группа уже наверху)
        if (стартовая) выбрать_клеточку(стартовая.id, { прокрутить: true });
    }

    function создать_блок_группы(имя_группы, список_гр) {
        const обёртка = document.createElement('section');
        обёртка.className = 'группа';
        обёртка.dataset.группа = имя_группы;

        const заголовок = document.createElement('button');
        заголовок.type = 'button';
        заголовок.className = 'группа-заголовок';
        заголовок.innerHTML = `
            <span class="группа-стрелка">▸</span>
            <span class="группа-имя">${ИМЕНА_ГРУПП[имя_группы] || имя_группы}</span>
            <span class="группа-счётчик">[${список_гр.length}]</span>
        `;
        заголовок.addEventListener('click', () => {
            const раскрыта_сейчас = обёртка.classList.contains('раскрыта');
            раскрыть_группу(имя_группы, !раскрыта_сейчас);
        });

        const список_эл = document.createElement('ul');
        список_эл.className = 'клеточки';

        for (const кл of список_гр) {
            const li = document.createElement('li');
            li.className = 'клеточка';
            li.dataset.id = кл.id;
            li.tabIndex = 0;
            li.innerHTML = `
                <span class="клеточка-точка"></span>
                <span class="клеточка-имя"></span>
            `;
            li.querySelector('.клеточка-имя').textContent = кл.название || кл.id;
            li.title = (кл.название || кл.id);
            li.addEventListener('click', () => выбрать_клеточку(кл.id));
            li.addEventListener('keydown', (e) => {
                if (e.key === 'Enter' || e.key === ' ') {
                    e.preventDefault();
                    выбрать_клеточку(кл.id);
                }
            });
            список_эл.appendChild(li);
        }

        обёртка.appendChild(заголовок);
        обёртка.appendChild(список_эл);
        return обёртка;
    }

    function раскрыть_группу(имя_группы, раскрыть) {
        const узел = контейнер_групп.querySelector(`.группа[data-группа="${CSS.escape(имя_группы)}"]`);
        if (!узел) return;
        узел.classList.toggle('раскрыта', раскрыть);
        const стрелка = узел.querySelector('.группа-стрелка');
        if (стрелка) стрелка.textContent = раскрыть ? '▾' : '▸';
    }

    function выбрать_клеточку(id, { прокрутить = false } = {}) {
        const данные = клеточки_по_id.get(id);
        if (!данные) return;

        // Снимаем старую активность
        корень_панели.querySelectorAll('.клеточка.активна').forEach(n => n.classList.remove('активна'));
        // Ставим новую
        const li = корень_панели.querySelector(`.клеточка[data-id="${CSS.escape(id)}"]`);
        if (li) {
            li.classList.add('активна');
            if (прокрутить) li.scrollIntoView({ block: 'nearest', behavior: 'auto' });
        }
        активный_id = id;
        обновить_паспорт(данные);

        // Шина событий (Решение 5.2). Также записываем «текущую» глобально,
        // чтобы Блоки 6/7, монтирующиеся ПОСЛЕ старта каталога, могли подхватить
        // выбор без необходимости в каталоге повторно эмитить событие.
        window.__текущая_клеточка = { id, данные };
        window.dispatchEvent(new CustomEvent('cellSelected', { detail: { id, данные } }));
    }

    function обновить_паспорт(d) {
        if (!узел_паспорта) return;
        const длительность = (typeof d['длительность_сек'] === 'number')
            ? d['длительность_сек'].toFixed(1)
            : '?';
        const атомы = d['число_атомов']?.toLocaleString('ru-RU') ?? '?';
        const элемент = d['основной_элемент'] || '—';
        const название = d['название'] || d.id;
        узел_паспорта.textContent =
            `${название} · ${длительность} сек · ${атомы} атомов · ${элемент}`;
    }

    // === Клавиатура: стрелки внутри группы (Решение 5.3) ===
    document.addEventListener('keydown', (e) => {
        if (e.key !== 'ArrowLeft' && e.key !== 'ArrowRight') return;
        if (!window.__каталог_в_фокусе) return;           // плеер обработает иначе
        if (!активный_id) return;
        const активная = клеточки_по_id.get(активный_id);
        if (!активная) return;

        const список_гр = группы.get(активная.группа);
        if (!список_гр || !список_гр.length) return;
        const idx = список_гр.findIndex(c => c.id === активный_id);
        if (idx < 0) return;

        const шаг = e.key === 'ArrowRight' ? 1 : -1;
        const новый_idx = (idx + шаг + список_гр.length) % список_гр.length; // циклически
        e.preventDefault();
        // Группа должна быть раскрыта (она должна была быть — но на всякий)
        раскрыть_группу(активная.группа, true);
        выбрать_клеточку(список_гр[новый_idx].id, { прокрутить: true });
    });
})();
