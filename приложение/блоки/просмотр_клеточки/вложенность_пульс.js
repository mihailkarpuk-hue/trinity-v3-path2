// вложенность_пульс.js
// ─────────────────────────────────────────────────────────────────────────
// Показ ВЗАИМОВЛОЖЕННОСТИ как СИНХРОННОСТИ пульсации атомов.
//
// Идея (см. ПАРАМЕТРЫ_104_в_образ.md): вложенность — это сцепка масштабов
// ВО ВРЕМЕНИ. Поэтому показываем её временем, а не формой:
//   • высокая вложенность → группы атомов (октавные полосы) дышат СИНХРОННО
//     (фазы совпадают) — масштабы «дышат как одно тело»;
//   • низкая вложенность → группы дышат ВРАЗНОБОЙ (случайные фазы) — рассыпано.
//
// Отдельный модуль — НЕ переписывает проекция_образ.js. Подключается одной
// строкой в цикле tick (см. блок «КАК ВСТАВИТЬ» внизу).
// ─────────────────────────────────────────────────────────────────────────

const _ПОЛОСЫ = [120, 240, 480, 960, 1920, 3840, 8000]; // те же октавы, что в анализаторе
const _N = _ПОЛОСЫ.length - 1;                          // 6 групп

function _clamp(v, a, b) { return v < a ? a : (v > b ? b : v); }

function _группа(freq) {
    for (let i = 0; i < _N; i++) {
        if (freq >= _ПОЛОСЫ[i] && freq < _ПОЛОСЫ[i + 1]) return i;
    }
    return freq < _ПОЛОСЫ[0] ? 0 : _N - 1;
}

/**
 * Создаёт пульс-функцию по паспорту клетки.
 * @param {object} p — { nestedness, mod_depth, mod_rate } из паспорта (оси_звука).
 * @returns {{пульс:(freq:number,tMs:number)=>number, nest:number}}
 *   пульс(freq, t) → множитель размера/яркости атома (около 1.0).
 */
export function создать_пульс_вложенности(p = {}) {
    const nest  = _clamp(p.nestedness ?? 0.0, 0, 1);
    const depth = _clamp(p.mod_depth  ?? 0.4, 0, 2);
    const rate  = _clamp(p.mod_rate   ?? 4.0, 0.3, 20);   // Гц

    // фаза каждой группы: при nest→1 все ≈0 (синхрон), при nest→0 — врозь
    const фазы = new Float32Array(_N);
    for (let g = 0; g < _N; g++) фазы[g] = (1 - nest) * Math.random() * 2 * Math.PI;

    const ампл = depth * 0.5; // размах ±depth/2 вокруг 1.0

    function пульс(freq, tMs) {
        const g = _группа(freq);
        const w = 2 * Math.PI * rate * (tMs / 1000) + фазы[g];
        return 1 + ампл * Math.sin(w);
    }
    return { пульс, nest, depth, rate };
}

