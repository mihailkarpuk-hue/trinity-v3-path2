// Тринити Альфа — Блок 6 «Просмотр клеточки»
// Главный модуль: монтирует 3 проекции, переключатель, слушает
// 'cellSelected' (Блок 5) и 'playbackTime' (Блок 7) для синхронной развёртки.

import { создать_проекцию_сцена } from './проекция_сцена.js';
import {
    создать_3d_среду,
    загрузить_атомы,
    собрать_контент,
} from './проекция_3d.js';
import { создать_образ_среду } from './проекция_образ.js';
import { создать_эталон_сцену } from './сцена_эталон.js';

const БАЗА_ДАННЫХ = '../../данные/клеточки/';
const ОСНОВНАЯ = 'образ';   // шов 7: Сцена ≡ атомы — образ по умолчанию

(() => {
    const зона = document.getElementById('зона-просмотр');
    if (!зона) { console.error('[просмотр] нет #зона-просмотр'); return; }

    зона.querySelector('.заглушка')?.remove();

    const корень = document.createElement('div');
    корень.className = 'просмотр-корень';
    зона.appendChild(корень);

    const сцена   = создать_проекцию_сцена(корень, { базовый_путь: БАЗА_ДАННЫХ });
    const атомы   = создать_3d_среду(корень, { класс: 'проекция-атомы' });
    const решётка = создать_3d_среду(корень, { класс: 'проекция-решётка' });
    const образ   = создать_образ_среду(корень);
    const эталон_сцена = создать_эталон_сцену(корень);   // 3D-модель явления для вкладки «Сцена»
    const проекции = { 'сцена': сцена, 'атомы': атомы, 'решётка': решётка, 'образ': образ };

    let активная = ОСНОВНАЯ;
    let текущая_клеточка = null;
    let режим_коорд = 'физика';   // алфавит: X=время · Y=частота · Z=амплитуда (структура звука)
    let цвет_режим = 'файл';    // 'файл' | 'hz' (цвет = частота)
    /** @type {Map<string, any>} */
    const кеш_атомов = new Map();

    // Переключатель режима координат (виден только на «Атомы»/«Решётка»)
    const узел_коорд = document.getElementById('переключатель-координат');
    function показать_коорд(активная_проекция) {
        if (!узел_коорд) return;
        узел_коорд.hidden = (активная_проекция === 'сцена');
    }
    document.querySelectorAll('.кх').forEach((b) => {
        b.addEventListener('click', () => {
            const р = b.dataset['режим'];
            if (!р || р === режим_коорд) return;
            режим_коорд = р;
            document.querySelectorAll('.кх').forEach(x => {
                const a = x.dataset['режим'] === р;
                x.classList.toggle('активна', a);
                x.setAttribute('aria-selected', a ? 'true' : 'false');
            });
            // Перерисуем активную 3D-проекцию
            if (текущая_клеточка && активная !== 'сцена') {
                применить_к_проекции(активная, текущая_клеточка);
            }
        });
    });

    // Переключатель цвета: «файл» / «Hz» (цвет = частота, спектральный образ)
    document.querySelectorAll('.цв').forEach((b) => {
        b.addEventListener('click', () => {
            const c = b.dataset['цвет'];
            if (!c || c === цвет_режим) return;
            цвет_режим = c;
            document.querySelectorAll('.цв').forEach(x => {
                const a = x.dataset['цвет'] === c;
                x.classList.toggle('активна', a);
                x.setAttribute('aria-selected', a ? 'true' : 'false');
            });
            if (текущая_клеточка && активная !== 'сцена') {
                применить_к_проекции(активная, текущая_клеточка);
            }
        });
    });

    function активировать(имя) {
        активная = имя;
        for (const [k, p] of Object.entries(проекции)) {
            if (k === имя) p.активировать(); else p.деактивировать();
        }
        if (имя !== 'сцена') эталон_сцена.деактивировать();   // прячем 3D-эталон вне «Сцены»
        document.querySelectorAll('.прж').forEach(b => {
            const a = b.dataset['проекция'] === имя;
            b.classList.toggle('активна', a);
            b.setAttribute('aria-selected', a ? 'true' : 'false');
        });
        показать_коорд(имя);
        if (текущая_клеточка) применить_к_проекции(имя, текущая_клеточка);
    }

    async function применить_к_проекции(имя, клеточка) {
        const прж = проекции[имя];
        if (имя === 'сцена') {
            // шов 7: буквица / без модели → Сцена ≡ Образ (атомы)
            const живая = String(клеточка['группа']||'').includes('буквица') || !клеточка['модель'];
            if (живая) {
                прж.деактивировать?.();
                эталон_сцена.деактивировать();
                проекции['образ'].активировать();
                активная = 'образ';
                let данные;
                if (клеточка['__в_памяти']) {
                    данные = window.__пользовательские?.['атомы']?.get(клеточка.id);
                } else if (клеточка['атомы']) {
                    const url_атомы = БАЗА_ДАННЫХ + клеточка['атомы'];
                    данные = кеш_атомов.get(url_атомы);
                    if (!данные) { данные = await загрузить_атомы(url_атомы); кеш_атомов.set(url_атомы, данные); }
                }
                if (данные) {
                    window.__текущие_атомы = данные;
                    window.dispatchEvent(new CustomEvent('atomsReady', { detail: { данные } }));
                    const ok = проекции['образ'].применить(данные, режим_коорд, цвет_режим,
                        клеточка?.['динамика']||'', клеточка?.['п104']||null, клеточка?.['параметры104']||null);
                    if (ok) проекции['образ'].setVisibleByTime(последнее_t_воспр);
                }
                return;
            }
            if (клеточка['модель']) {
                // Реальная 3D-сцена явления (свой рендер) — синхронна звуку
                // через analyser (см. сцена_эталон.js).
                прж.деактивировать?.();
                эталон_сцена.активировать();
                try { await эталон_сцена.показать(БАЗА_ДАННЫХ + клеточка['модель']); }
                catch (e) { console.error('[эталон-сцена] ошибка:', e); }
            } else {
                // Реальной 3D-модели нет → показываем «Образ» (он тоже синхронен звуку).
                эталон_сцена.деактивировать();
                const b = document.querySelector('.прж[data-проекция="образ"]');
                if (b) b.click();
            }
            return;
        }
        try {
            let данные;
            if (клеточка['__в_памяти']) {
                // Пользовательский звук: атомы уже в памяти (атомизатор «на лету»).
                данные = window.__пользовательские?.['атомы']?.get(клеточка.id);
                if (!данные) throw new Error('атомы пользовательской клеточки не найдены');
            } else {
                if (!клеточка['атомы']) {
                    прж.показать_индикатор('Нет файла атомов — полный корпус клеточек не в git');
                    return;
                }
                const url_атомы = БАЗА_ДАННЫХ + клеточка['атомы'];
                прж.показать_индикатор('Загружаю атомы…');
                данные = кеш_атомов.get(url_атомы);
                if (!данные) {
                    данные = await загрузить_атомы(url_атомы);
                    кеш_атомов.set(url_атомы, данные);
                }
            }
            прж.спрятать_индикатор();
            // Отдаём текущие атомы наружу — для обратной буквы «образ → звук».
            window.__текущие_атомы = данные;
            window.dispatchEvent(new CustomEvent('atomsReady', { detail: { данные } }));

            // ОБРАЗ — единая сцена из атомов по алфавиту (свой рендер).
            if (имя === 'образ') {
                const ok = прж.применить(данные, режим_коорд, цвет_режим, клеточка?.['динамика']||'', клеточка?.['п104']||null, клеточка?.['параметры104']||null);
                if (!ok) { прж.показать_индикатор('Тихий звук — атомов мало'); return; }
                прж.setVisibleByTime(последнее_t_воспр);
                return;
            }

            const контент = собрать_контент(данные, имя === 'решётка' ? 'решётка' : 'атомы', режим_коорд, цвет_режим);
            if (!контент) {
                прж.заменить_содержимое({ облако_новое: null, рёбра_новые: null, births_новые: null });
                прж.показать_индикатор('Тихий звук — атомов мало');
                return;
            }
            прж.заменить_содержимое(контент);
            прж.пометить_режим?.(режим_коорд);
            // Сразу применим последнее известное время (обычно 0 после смены клеточки)
            прж.setVisibleByTime(последнее_t_воспр);
        } catch (e) {
            console.error('[просмотр] ошибка загрузки атомов:', e);
            прж.показать_индикатор('Не удалось загрузить атомы');
        }
    }

    // Подписки на шину событий.
    // По умолчанию облако «полное» (Infinity). Развёртка по времени
    // начинается только когда плеер реально играет (playbackStarted →
    // playbackTime → … → playbackPaused/Ended).
    let последнее_t_воспр = Infinity;
    let играет = false;
    window.addEventListener('cellSelected', (e) => {
        const клеточка = e.detail?.['данные'];
        if (!клеточка) return;
        текущая_клеточка = клеточка;
        // При смене клеточки — снова показываем всё (плеер на паузе).
        последнее_t_воспр = Infinity;
        играет = false;
        // Нет реальной 3D-модели → уводим со «Сцены» на «Образ».
        if (!клеточка['модель'] && активная === 'сцена') {
            const b = document.querySelector('.прж[data-проекция="образ"]');
            if (b) { b.click(); return; }   // клик активирует «Образ» и отрисует
        }
        применить_к_проекции(активная, клеточка);
    });
    window.addEventListener('playbackStarted', () => {
        играет = true;
        последнее_t_воспр = 0;
        проекции['атомы'].setVisibleByTime(0);
        проекции['решётка'].setVisibleByTime(0);
        проекции['образ'].setVisibleByTime(0);
    });
    window.addEventListener('playbackPaused', () => { играет = false; });
    window.addEventListener('playbackEnded',  () => { играет = false; });
    window.addEventListener('playbackTime', (e) => {
        // Время от плеера — обрабатываем только пока он реально играет.
        if (!играет) return;
        const t = +e.detail?.t || 0;
        последнее_t_воспр = t;
        проекции['атомы'].setVisibleByTime(t);
        проекции['решётка'].setVisibleByTime(t);
        проекции['образ'].setVisibleByTime(t);
    });

    // Переключатель из Задания 4
    document.querySelectorAll('.прж').forEach((b) => {
        b.addEventListener('click', () => {
            const имя = b.dataset['проекция'];
            if (имя && имя in проекции && имя !== активная) активировать(имя);
        });
    });

    активировать(ОСНОВНАЯ);

    // Мост в сцену для плеера (Решение 1, основной путь — postMessage)
    window.__просмотр = {
        отправить_в_сцену: (msg) => сцена.отправить(msg),
        нажать_в_сцене:    (sel) => сцена.нажать_в_сцене(sel),
        текущая_проекция:  () => активная,
    };

    // Если каталог уже выбрал клеточку до нашего монтажа — подхватим
    const уже_выбрана = window.__текущая_клеточка?.['данные'];
    if (уже_выбрана) {
        текущая_клеточка = уже_выбрана;
        последнее_t_воспр = Infinity;
        применить_к_проекции(активная, уже_выбрана);
    }
})();
